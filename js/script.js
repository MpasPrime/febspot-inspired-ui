let currentLanguage = "pt";
let currentQuery = "";
let currentCategory = "";

function translate(key) {
  return translations[currentLanguage][key] ??
    translations.en[key] ?? key;
}

function localizedTitle(video) {
  return video.title[currentLanguage] || video.title.en;
}

function formatViews(number) {
  const locale = {
    pt:"pt-BR", en:"en-US", es:"es-ES", fr:"fr-FR"
  }[currentLanguage];

  return new Intl.NumberFormat(locale, {
    notation:"compact",
    maximumFractionDigits:1
  }).format(number) + " " + translate("views");
}

function formatAge(minutes) {
  if (minutes < 60) {
    return translate("minutes").replace("{n}", minutes);
  }
  return translate("hours").replace("{n}", Math.floor(minutes / 60));
}

function createCard(video) {
  const card = document.createElement("article");
  card.className = "video-card";

  const title = localizedTitle(video);
  const category = translate(video.category === "Travel" ? "travel" :
    video.category === "Animals" ? "animals" :
    video.category === "Sports" ? "sports" :
    video.category === "Nature" ? "nature" :
    video.category === "Education" ? "education" : "lifestyle");

  card.dataset.search = (
    title + " " + category + " " + video.category
  ).toLocaleLowerCase();

  card.dataset.category = video.category;

  const thumbnail = document.createElement("div");
  thumbnail.className = "thumbnail";

  const img = document.createElement("img");
  img.src = "https://images.unsplash.com/" + video.image +
    "?auto=format&fit=crop&w=640&q=80";
  img.alt = title;
  img.loading = "lazy";
  img.decoding = "async";

  thumbnail.appendChild(img);

  const tag = document.createElement("span");
  tag.className = "video-category";
  tag.textContent = category;

  const heading = document.createElement("h3");
  heading.className = "video-title";
  heading.textContent = title;

  const meta = document.createElement("p");
  meta.className = "video-meta";
  meta.textContent = formatViews(video.views) + " · " + formatAge(video.age);

  card.append(thumbnail, tag, heading, meta);
  return card;
}

function renderVideos() {
  const grids = {
    trending:document.getElementById("trendingGrid"),
    popular:document.getElementById("popularGrid"),
    recent:document.getElementById("recentGrid")
  };

  Object.values(grids).forEach(grid => grid.replaceChildren());

  videos.forEach(video => {
    if (video.group === "trending") {
      grids.trending.appendChild(createCard(video));
    } else if (video.group === "popular") {
      grids.popular.appendChild(createCard(video));
    } else {
      grids.recent.appendChild(createCard(video));
    }
  });

  applyFilters();
}

function applyFilters() {
  let visibleCount = 0;

  document.querySelectorAll(".video-card").forEach(card => {
    const matchesQuery = !currentQuery ||
      card.dataset.search.includes(currentQuery);

    const matchesCategory = !currentCategory ||
      card.dataset.category === currentCategory;

    const visible = matchesQuery && matchesCategory;

    card.style.display = visible ? "" : "none";

    if (visible) visibleCount++;
  });

  document.getElementById("emptyMessage").style.display =
    visibleCount ? "none" : "block";

  ["trendingGrid", "popularGrid", "recentGrid"].forEach(id => {
    const grid = document.getElementById(id);
    const section = grid.closest(".section");
    const hasVisibleCards = [...grid.children].some(
      card => card.style.display !== "none"
    );
    section.style.display = hasVisibleCards ? "" : "none";
  });
}

function setLanguage(language) {
  currentLanguage = translations[language] ? language : "en";

  document.documentElement.lang = {
    pt:"pt-BR", en:"en", es:"es", fr:"fr"
  }[currentLanguage];

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    element.textContent = translate(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    element.placeholder = translate(element.dataset.i18nPlaceholder);
  });

  document.getElementById("copyStatus").textContent = "";
  renderVideos();
}

document.getElementById("languageSelect").addEventListener("change", event => {
  setLanguage(event.target.value);
});

document.getElementById("searchForm").addEventListener("submit", event => {
  event.preventDefault();
  currentQuery = document.getElementById("searchInput")
    .value.trim().toLocaleLowerCase();
  currentCategory = "";
  document.querySelectorAll(".category").forEach(link => {
    link.style.borderColor = "";
  });
  applyFilters();
});

document.getElementById("categoryList").addEventListener("click", event => {
  const link = event.target.closest("[data-category]");
  if (!link) return;

  currentCategory = link.dataset.category;
  currentQuery = "";
  document.getElementById("searchInput").value = "";

  document.querySelectorAll(".category").forEach(item => {
    item.style.borderColor =
      item === link ? "var(--accent)" : "";
  });

  applyFilters();
});

document.getElementById("copyReferral").addEventListener("click", async () => {
  const status = document.getElementById("copyStatus");

  try {
    await navigator.clipboard.writeText("https://www.febspot.com/");
    status.textContent = translate("copied");
  } catch {
    status.textContent = translate("copyError");
  }
});

document.querySelectorAll(".nav-link").forEach(link => {
  link.addEventListener("click", () => {
    document.querySelectorAll(".nav-link").forEach(item => {
      item.classList.remove("active");
    });
    link.classList.add("active");
  });
});

